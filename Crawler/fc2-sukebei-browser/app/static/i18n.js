let lang = 'en';
try {
  lang = localStorage.getItem('fc2sb.lang') || (navigator.language.startsWith('ja') ? 'ja' : 'en');
} catch { /* storage unavailable */ }

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  try { localStorage.setItem('fc2sb.lang', lang); } catch { /* ignore */ }
  applyStatic();
}

export function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

// Translate the static markup: data-i18n (text), data-i18n-placeholder, data-i18n-title.
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
